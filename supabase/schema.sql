-- Run this in Supabase SQL Editor.
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  subject text not null,
  message text not null,
  created_at timestamptz not null default now()
);
alter table public.contact_messages enable row level security;
-- Visitors may submit contact forms, but cannot read or modify submissions.
create policy "Anyone can submit a contact message"
on public.contact_messages for insert to anon, authenticated
with check (
  length(trim(name)) between 1 and 120 and
  length(trim(email)) between 3 and 254 and
  length(trim(subject)) between 1 and 200 and
  length(trim(message)) between 1 and 5000
);
